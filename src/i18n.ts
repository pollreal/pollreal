// English at "/", every other language under its own prefix ("/ko/…", "/ja/…"). hi = Hindi, zh = Simplified Chinese.
export const LANGS = ['en', 'ko', 'es', 'fr', 'hi', 'de', 'ja', 'zh', 'ru'] as const
export type Lang = (typeof LANGS)[number]
export const isLang = (s: unknown): s is Lang => typeof s === 'string' && (LANGS as readonly string[]).includes(s)
export const LANG_NAMES: Record<Lang, string> = {
  en: 'English',
  ko: '한국어',
  es: 'Español',
  fr: 'Français',
  hi: 'हिन्दी',
  de: 'Deutsch',
  ja: '日本語',
  zh: '中文',
  ru: 'Русский',
}

export const prefix = (lang: Lang) => (lang === 'en' ? '' : `/${lang}`)
export const href = (lang: Lang, path: string) => (lang === 'en' ? path || '/' : path === '/' ? `/${lang}` : `/${lang}${path}`)
// The language of a request path and the same path without its prefix.
export function langOfPath(path: string): Lang {
  const seg = path.split('/')[1] ?? ''
  return isLang(seg) && seg !== 'en' ? seg : 'en'
}
export function stripLang(path: string) {
  const lang = langOfPath(path)
  if (lang === 'en') return path
  return path === `/${lang}` ? '/' : path.slice(lang.length + 1)
}

