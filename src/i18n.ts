const DICTS: Record<Lang, Dict> = { en, ko, es, fr, hi, de, ja, zh, ru }
export const tr = (lang: Lang): Dict => DICTS[lang]

// Validation and other library code returns message keys; views turn them into text here.
export type Msg = { k: string; p?: (string | number)[] }
export function msgText(lang: Lang, m: Msg): string {
  const d = tr(lang) as unknown as Record<string, unknown>
  const [head, tail] = m.k.split('.')
  const v = tail ? (d[head as string] as Record<string, unknown> | undefined)?.[tail] : d[head as string]
  if (typeof v === 'function') return (v as (...a: (string | number)[]) => string)(...(m.p ?? []))
  return typeof v === 'string' ? v : m.k
}
